async function main() {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Euronics eshop";
  const head = (ws: ExcelJS.Worksheet, row: number) => {
    const r = ws.getRow(row); r.font = { bold: true }; r.alignment = { vertical: "middle", wrapText: true }; r.height = 42;
    r.eachCell((c) => { c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFEAF1FA" } }; c.border = { bottom: { style: "thin" } }; });
  };

  const ws = wb.addWorksheet("Χωρίς τιμή");
  ws.mergeCells("A1:I1");
  ws.getCell("A1").value = "Περιοχές χωρίς τιμή αποστολής — συμπληρώστε τα ποσά (€, ανά συσκευή). Όσο μένουν κενά, το eshop ΔΕΝ παραδίδει στο σπίτι σε αυτές τις περιοχές.";
  ws.getCell("A1").font = { bold: true, size: 12 };
  ws.getRow(1).height = 30; ws.getCell("A1").alignment = { wrapText: true, vertical: "middle" };
  ws.getRow(2).values = ["Περιοχή", "Περιοχή/Νομός", "Τ.Κ.", ...CLASSES, "Σχόλιο"];
  head(ws, 2);
  for (const a of AREAS) ws.addRow([a.name, a.region, a.zips.join(", "), null, null, null, null, null, ""]);
  for (let i = 0; i < 8; i++) ws.addRow(["", "", "", null, null, null, null, null, "— κενή γραμμή για δική σας προσθήκη"]);
  ws.columns = [{ width: 24 }, { width: 18 }, { width: 14 }, ...CLASSES.map(() => ({ width: 15 })), { width: 40 }];
  ws.views = [{ state: "frozen", ySplit: 2 }];

  const ws2 = wb.addWorksheet("Ερωτήσεις");
  ws2.getRow(1).values = ["Ερώτηση", "Απάντησή σας"];
  head(ws2, 1);
  for (const q of QUESTIONS) ws2.addRow(q);
  ws2.columns = [{ width: 95 }, { width: 40 }];
  ws2.getColumn(1).alignment = { wrapText: true, vertical: "middle" };

  const ws3 = wb.addWorksheet("Συμφωνημένες");
  ws3.getRow(1).values = ["Περιοχή", "Περιοχή/Νομός", "Τ.Κ.", ...CLASSES];
  head(ws3, 1);
  for (const r of AGREED) ws3.addRow(r);
  ws3.columns = [{ width: 24 }, { width: 18 }, { width: 14 }, ...CLASSES.map(() => ({ width: 15 }))];
  ws3.views = [{ state: "frozen", ySplit: 1 }];

  const out = "docs/apostoles-times-perioxon.xlsx";
  await wb.xlsx.writeFile(out);
  console.log(`✓ ${out} · ${AREAS.length} περιοχές χωρίς τιμή · ${QUESTIONS.length} ερωτήσεις · ${AGREED.length} συμφωνημένες`);
}
main();
