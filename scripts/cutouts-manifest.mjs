#!/usr/bin/env node
// Writes lib/data/cutouts.generated.ts: the set of product photos that have a
// transparent cutout in public/img/cutouts (same basename, .png).
// Usage: node scripts/cutouts-manifest.mjs [--exclude name1,name2]
import { readdirSync, writeFileSync } from "node:fs";
const ex = new Set((process.argv.find((a) => a.startsWith("--exclude="))?.slice(10) ?? "").split(",").filter(Boolean));
const names = readdirSync("public/img/cutouts").filter((f) => f.endsWith(".webp")).map((f) => f.slice(0, -5)).filter((n) => !ex.has(n)).sort();
writeFileSync("lib/data/cutouts.generated.ts", `// Generated by scripts/cutouts-manifest.mjs — do not edit.\nexport const CUTOUTS: ReadonlySet<string> = new Set(${JSON.stringify(names)});\n`);
console.log(names.length, "cutouts");
