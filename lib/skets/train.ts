export interface TurnOut { route?: string; to?: string; alt?: string; ready?: boolean; why?: string; say?: string; i?: number; said?: string; heard?: string }

/** Τι έκανε ο Ερμής, σε μορφή που συγκρίνεται: script · alt:<κλειδί> · ready:<απάντηση> · clarify · free · store:<n> · none */
export function outcome(o: TurnOut): string {
  if (o.route === "jump" || o.route === "alt") return o.alt ? `alt:${o.alt}` : "script";
  if (o.route === "store") return `store:${o.i ?? 0}`;
  if (o.route === "free") return o.ready ? (o.why === "unheard" || o.why?.startsWith("model-") ? "clarify" : `ready:${o.say ?? ""}`) : "free";
  return o.route === "none" ? "none" : "script";
}

