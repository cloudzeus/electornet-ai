/** Όνομα νομού σε οποιαδήποτε γραφή → κανονική εγγραφή. */
export const districtByName = (raw: string | null | undefined): DistrictDef | null => (raw ? BY_FOLD.get(foldGreek(raw)) ?? null : null);
/** Κωδικός SoftOne DISTRICT → κανονική εγγραφή. */
export const districtByS1 = (code: string | number | null | undefined): DistrictDef | null => (code == null ? null : DISTRICTS.find((d) => d.s1 === Number(code)) ?? null);
/** Τ.Κ. → νομός (από τα δύο πρώτα ψηφία). */
export const districtByZip = (zip: string | null | undefined): DistrictDef | null => (zip ? BY_ZIP.get(zip.replace(/\D/g, "").slice(0, 2)) ?? null : null);
/** Οτιδήποτε ξέρουμε → περιφέρεια. Προτεραιότητα: Τ.Κ. (πιο αξιόπιστο) → όνομα νομού. */
export function regionOf(input: { zip?: string | null; district?: string | null; s1?: string | number | null }): Region | null {
  return (districtByS1(input.s1) ?? districtByZip(input.zip) ?? districtByName(input.district))?.region ?? null;
}
/** Οι νομοί μιας περιφέρειας. */
export const districtsOfRegion = (region: Region) => DISTRICTS.filter((d) => d.region === region);
