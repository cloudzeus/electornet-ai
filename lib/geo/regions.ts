export function foldGreek(s: string): string {
  return s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/[^Α-ΩA-Z]/g, "")
    .replace(/Σ$/, "");
}

