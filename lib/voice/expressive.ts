/**
 * Χρωματισμός της φωνής ανά πρόταση (audio tags του ElevenLabs v3): ο Ερμής δεν λέει τα πάντα με τον ίδιο τόνο.
 * Ερώτηση → περιέργεια, οικονομία / προσφορά → χαρά, πρόταση → σιγουριά, κακό νέο → σκεπτικός τόνος, χαιρετισμός → ζεστασιά.
 * Κανόνες, όχι AI: ντετερμινιστικό (ίδιο κείμενο → ίδιος ήχος → η cache δουλεύει), χωρίς κόστος και καθυστέρηση.
 * Η πρώτη πρόταση παίρνει τα βασικά tags της ρύθμισης· ίδιο tag δεν επαναλαμβάνεται σε διαδοχικές προτάσεις.
 */
const RULES: [RegExp, string][] = [
  [/(δυστυχώς|λυπάμαι|δεν (υπάρχει|έχουμε|βρήκα|το έχουμε)|εξαντλ|δεν διατίθεται)/iu, "[thoughtful]"],
  [/(προσοχή|πρόσεξε|να ξέρεις|μην ξεχάσεις|σημαντικό)/iu, "[serious]"],
  [/(γλιτών|εξοικονόμ|έκπτωσ|προσφορ|φθηνότερ|δώρο|άτοκ|κερδίζεις|χαμηλότερη τιμή)/iu, "[happy]"],
  [/(καλώς|γεια σου|χαίρομαι|ευχαριστώ|καλή σου μέρα)/iu, "[warm]"],
  [/(σου προτείνω|προτείνω|θα διάλεγα|ιδανικ|σου ταιριάζει|η καλύτερη επιλογή|το πιο κατάλληλο)/iu, "[confident]"],
];

export function expressive(text: string, base = ""): string {
  const sentences = text.split(/(?<=[.!?…])\s+(?=\S)/u);
  let last = "";
  return sentences.map((s, i) => {
    let tag = s.trim().endsWith("?") ? "[curious]" : s.trim().endsWith("!") ? "[excited]" : RULES.find(([re]) => re.test(s))?.[1] ?? "";
    if (i === 0 && !tag) tag = base;
    if (tag && tag === last) tag = "";
    if (tag) last = tag;
    return tag ? `${tag} ${s}` : s;
  }).join(" ").trim();
}
