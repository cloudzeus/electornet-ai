/**
 * Χαρακτηριστικά σύγκρισης από την περιγραφή του ERP, εκεί όπου ο τύπος δεν έχει (αρκετά) δικά του φίλτρα.
 * Π.χ. τα «Handsfree Bluetooth» έχουν στο SoftOne ΜΟΝΟ το φίλτρο «Εταιρία» — αλλά οι περιγραφές τους γράφουν
 * έκδοση Bluetooth, αυτονομία, βάρος, αντίσταση. Κάθε κατασκευαστής τα ονομάζει αλλιώς («Ανεξαρτήσια Ακουστικών»,
 * «Ώρες Λειτουργίας», «ΖΩΗ ΜΠΑΤΑΡΙΑΣ»), οπότε εδώ τα φέρνουμε στο ίδιο όνομα για να πέσουν στην ίδια γραμμή.
 * Η σύγκριση κρατά μια γραμμή μόνο όταν έχουν τιμή τουλάχιστον δύο προϊόντα, άρα ό,τι δεν ταιριάζει απλώς δεν φαίνεται.
 * Καθαρό module.
 */
const lower = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/ς/g, "σ").replace(/\s+/g, " ").trim();

/** Ίδιο μέγεθος με άλλο όνομα → ένα όνομα. Γενικά μεγέθη (βάρος, αυτονομία, σύνδεση), όχι ειδικά μιας κατηγορίας. */
const SAME: [RegExp, string][] = [
  [/^(εκδοση bluetooth|bluetooth εκδοση|bluetoothbluetooth|bluetooth version|version)$/, "Έκδοση Bluetooth"],
  [/^(αντισταση( ηχειου)?|speaker impedance)$/, "Αντίσταση"],
  [/^(ευαισθησια( \(@ ?1 ?khz\))?|αισθητικοτητα|speaker sensitivity.*)$/, "Ευαισθησία"],
  [/^(αποκριση συχνοτητασ|συχνοτητα( ακουστικων)?|speaker frequency response)$/, "Απόκριση συχνότητας"],
  [/^(ανεξαρτησια|αυτονομια|χρονοσ λειτουργιασ|ωρεσ λειτουργιασ|ζωη μπαταριασ|διαρκεια (ζωησ )?μπαταριασ|χρονοσ αναπαραγωγησ)/, "Αυτονομία"],
  [/^χρονοσ (επανα)?φορτ(ισ|ωσ)ησ/, "Χρόνος φόρτισης"],
  [/^((συνολικο |καθαρο )?βαροσ( τεμ| κυριασ μοναδασ| συσκευησ| προιοντοσ)?|weight.*)$/, "Βάρος"],
  [/^(θυρα φορτισησ.*|πηγη φορτισησ|charging interface)$/, "Θύρα φόρτισης"],
  [/^(διαμετροσ( ηχειου| ηχειων| audio drivers| οδηγου)?|driver unit|μοναδα οδηγησησ)$/, "Διάμετρος οδηγού"],
  [/^(τυποσ συνδεσησ|συνδεση|συνδεσιμοτητα|connector|ενσυρματεσ συνδεσεισ)$/, "Σύνδεση"],
  [/^(αποκωδικοποιηση ηχου|audio codecs?|codecs?)$/, "Codecs ήχου"],
  [/^(ασυρματη εμβελεια|εμβελεια|ασυμαρτη εμβελεια.*|ασυρματη εμβελεια.*)$/, "Εμβέλεια"],
  [/^(water resistant|αδιαβροχ[οα]|αντοχη στο νερο|προστασια ip.*|βαθμοσ προστασιασ.*|κωδικοσ διεθνουσ προστασιασ.*|ανθεκτικα στον ιδρωτα.*)$/, "Αντοχή στο νερό"],
  [/^([mμ]ικροφωνο|mic|τυποσ μικροφωνου)$/, "Μικρόφωνο"],
  [/^(active noise cancell?ation|noise cancell?ing|ενεργη ακυρωση θορυβου|ακυρωση θορυβου|εξουδετερωση θορυβου|anc)$/, "Ακύρωση θορύβου"],
  [/^((bluetooth )?chipsets?|chip)$/, "Chipset"],
  [/^(τυποσ ακουστικ(ου|ων)|τυποσ)$/, "Τύπος"],
  [/^(μπαταρια( ακουστικων)?|χωρητικοτητα μπαταριασ|battery capacity)$/, "Μπαταρία"],
  [/^(ισχυσ|ονομαστικη ισχυσ|ισχυσ εξοδου|power)$/, "Ισχύς"],
  [/^(υλικο( κατασκευησ)?)$/, "Υλικό"],
];
/** Δεν είναι χαρακτηριστικό του προϊόντος (συσκευασία, κωδικοί), ή υπάρχει ήδη αλλού στη σύγκριση (διαστάσεις, ενεργειακή κλάση — η δεύτερη μόνο από την ετικέτα, ποτέ από την περιγραφή). */
const SKIP = /ενεργειακ\S* κλαση|κλαση ενεργειακ|συσκευασ|πακετ|κουτι|χαρτοκιβ|περιεχομεν|εγγυησ|barcode|^ean|^κωδικοσ( προιοντοσ| ειδουσ| κατασκευαστη)?$|^sku$|^διαστασ|^dimensions|^product dimensions|^μαρκα$|^κατασκευαστησ$|^μοντελο$|^ηλικια$/;

const tidy = (key: string) => { const k = key.replace(/\s+/g, " ").replace(/\s*:$/, "").trim(); return k.length > 3 && k === k.toLocaleUpperCase("el-GR") && /[Α-ΩA-Z]{4}/.test(k) ? k.charAt(0) + k.slice(1).toLocaleLowerCase("el-GR") : k; };

export const canonSpecKey = (key: string): string | null => { const l = lower(key); if (!l || SKIP.test(l)) return null; return SAME.find(([re]) => re.test(l))?.[1] ?? tidy(key); };

export interface CompareAttr { key: string; value: string; group: string }
const LABEL_GROUP = "Από την ενεργειακή ετικέτα";

/** `have`: όσα δίνουν ήδη τα φίλτρα του τύπου — αυτά προηγούνται, η περιγραφή μόνο συμπληρώνει. */
export function specAttrs(specs: { group?: string | null; key: string; value: string }[], have: { key: string }[]): CompareAttr[] {
  const seen = new Set(have.map((a) => lower(a.key))), out: CompareAttr[] = [];
  for (const s of specs) {
    const key = canonSpecKey(s.key), value = s.value?.replace(/\s+/g, " ").trim();
    if (!key || !value || value.length > 70 || seen.has(lower(key))) continue;
    seen.add(lower(key));
    out.push({ key, value, group: s.group === LABEL_GROUP ? LABEL_GROUP : "Τεχνικά χαρακτηριστικά" });
  }
  return out;
}
