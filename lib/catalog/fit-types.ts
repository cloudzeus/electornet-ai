/**
 * Σε ποιους τύπους προϊόντος έχει νόημα το «Χωράει στον χώρο μου;».
 * Ο έλεγχος συγκρίνει το προϊόν με μια εσοχή και τη στενότερη πόρτα του σπιτιού — αυτό αφορά ό,τι μπαίνει σε
 * σταθερή θέση ή δύσκολα περνά από την πόρτα: λευκές συσκευές, τηλεοράσεις και έπιπλά τους, κλιματιστικά τοίχου,
 * όργανα γυμναστικής. Σε κινητό, σεσουάρ ή καφετιέρα η ερώτηση είναι θόρυβος, ακόμη κι αν ξέρουμε τις διαστάσεις
 * (οι διαστάσεις μένουν για το AR και τα χαρακτηριστικά — εδώ κρίνεται μόνο αν ΠΡΟΤΕΙΝΟΥΜΕ τον έλεγχο).
 * Καθαρό module: το διαβάζουν και server και client.
 */
const lower = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/ς/g, "σ");

/** Πάνω στη διαδρομή «Master › Main › τύπος» (ονόματα SoftOne, πεζά χωρίς τόνους). */
const FIT: RegExp[] = [
  /^λευκεσ συσκευεσ(?!.*αξεσουαρ)/, // πλυντήρια, ψυγεία, κουζίνες, εντοιχιζόμενα, απορροφητήρες, μικροκυμάτων
  /› τηλεορασεισ$|› επιπλα tv$/,
  /› κλιματιστικα inverter$|› ημιεπαγγελματικα$/, // η εσωτερική μονάδα θέλει συγκεκριμένο πλάτος τοίχου
  /› οργανα γυμναστικησ$/,
];

/** `path`: ονόματα από το Master ως τον τύπο. */
export const fitMatters = (path: string[]) => { const p = lower(path.join(" › ")); return FIT.some((re) => re.test(p)); };

/** Οι κατηγορίες των δειγματικών προϊόντων (fixtures), με τα δικά τους slugs. */
const DEMO_FIT = new Set(["tileoraseis", "air-condition", "plyntiria", "stegnotiria", "psygeia", "koyzines", "leykes-syskeyes"]);
export const demoFitMatters = (category: string, subcategory: string) => DEMO_FIT.has(subcategory) || DEMO_FIT.has(category);

/** Ερώτηση προς τον σύμβουλο που αφορά χώρο — δεν προτείνεται εκεί όπου ο έλεγχος δεν έχει νόημα. */
export const isFitQuestion = (q: string) => /χωρα(ει|νε)|στον χωρο μου|εσοχη/.test(lower(q));
